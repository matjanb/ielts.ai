// One-time backfill: assign a difficulty to every test_section.
//
// Reading sections store the passage body in `instructions`; we compute the
// Flesch Reading Ease of that text and bucket it (higher score = easier text).
// Listening sections have no readable text, so they default to 'medium'.
//
// Reads sections via the Supabase REST API (service-role key from .env.local)
// and writes UPDATE statements to 009b_section_difficulty_backfill.sql.
// This does NOT touch the DB itself — paste the generated SQL into the editor.
//
//   node scripts/compute-section-difficulty.mjs

import { readFileSync, writeFileSync } from 'node:fs'

function env(key) {
  const line = readFileSync('.env.local', 'utf8').split('\n').find(l => l.startsWith(key + '='))
  if (!line) throw new Error(`${key} missing from .env.local`)
  return line.slice(key.length + 1).trim().replace(/^['"]|['"]$/g, '')
}

const URL = env('NEXT_PUBLIC_SUPABASE_URL')
const KEY = env('SUPABASE_SERVICE_ROLE_KEY')

// crude syllable counter: count vowel groups, drop a trailing silent 'e'
function syllables(word) {
  word = word.toLowerCase().replace(/[^a-z]/g, '')
  if (word.length <= 3) return word.length ? 1 : 0
  word = word.replace(/(?:[^laeiouy]es|ed|[^laeiouy]e)$/, '').replace(/^y/, '')
  const groups = word.match(/[aeiouy]{1,2}/g)
  return Math.max(1, groups ? groups.length : 1)
}

function flesch(text) {
  const clean = text.replace(/\\n/g, ' ')
  const sentences = (clean.match(/[.!?]+/g) || []).length || 1
  const words = (clean.match(/[A-Za-z]+/g) || [])
  if (words.length < 40) return null // too little prose to judge (e.g. listening forms)
  const syl = words.reduce((s, w) => s + syllables(w), 0)
  return 206.835 - 1.015 * (words.length / sentences) - 84.6 * (syl / words.length)
}

function bucket(score) {
  if (score == null) return 'medium'
  if (score >= 60) return 'easy'
  if (score >= 40) return 'medium'
  return 'hard'
}

const headers = { apikey: KEY, Authorization: `Bearer ${KEY}` }
const get = async (path) => {
  const r = await fetch(`${URL}/rest/v1/${path}`, { headers })
  const j = await r.json()
  if (!Array.isArray(j)) throw new Error(`REST error for ${path}: ${JSON.stringify(j)}`)
  return j
}

const tests = await get('tests?select=id,type&limit=5000')
const typeById = new Map(tests.map(t => [t.id, t.type]))
const sections = await get('test_sections?select=id,test_id,instructions&limit=5000')

const lines = []
const tally = {}
for (const s of sections) {
  const type = typeById.get(s.test_id)
  let level
  if (type === 'reading') level = bucket(flesch(s.instructions || ''))
  else level = 'medium' // listening / writing
  tally[`${type}:${level}`] = (tally[`${type}:${level}`] || 0) + 1
  lines.push(`update test_sections set difficulty = '${level}' where id = '${s.id}';`)
}

const sql = [
  '-- Generated by scripts/compute-section-difficulty.mjs — section difficulty backfill.',
  '-- Reading: Flesch reading-ease buckets; Listening/Writing: medium.',
  '',
  ...lines,
  '',
].join('\n')

writeFileSync('supabase/migrations/009b_section_difficulty_backfill.sql', sql)
console.log(`Wrote ${lines.length} updates. Distribution:`)
for (const [k, n] of Object.entries(tally).sort()) console.log(`  ${n.toString().padStart(4)}  ${k}`)
